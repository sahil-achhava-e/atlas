'use strict';
/**
 * Generate the browser bridge's method table from preload/index.ts.
 *
 * The table maps `window.cth.foo()` to the ipcMain channel it invokes, and the
 * authority for that mapping is preload — it is the same file the Electron build
 * uses. Maintaining a second copy by hand is how browser mode shipped twice with
 * the renderer calling `spawnPty` while the bridge only knew `ptySpawn`: the
 * call fell through to the Proxy, resolved undefined, and the page died on the
 * result. So: read preload, write the map, and let a rename break the build
 * instead of the app.
 *
 * Three shapes are extracted, because the page has to treat them differently:
 *   invoke   → a POST, promise in, promise out
 *   sendSync → a BLOCKING XHR (the store reads two of these before first paint)
 *   on       → an SSE subscription, addressed per-pty when the channel is a
 *              template string
 */
const { readFileSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');

const ROOT = join(__dirname, '..');
const src = readFileSync(join(ROOT, 'src/preload/index.ts'), 'utf8');

const invoke = {}, sync = {}, events = {}, ptyEvents = {};

// Each `name: (...) => ...` member of the exposed object, with the body that
// follows it up to the next member at the same indent.
const members = [...src.matchAll(/\n  ([a-zA-Z_][\w]*)\s*:\s*(?:async\s*)?\(/g)];
for (let i = 0; i < members.length; i++) {
  const name = members[i][1];
  const body = src.slice(members[i].index, members[i + 1]?.index ?? src.length);

  const inv = body.match(/ipcRenderer\.invoke\(\s*'([^']+)'/);
  if (inv) { invoke[name] = inv[1]; continue; }

  const syn = body.match(/ipcRenderer\.sendSync\(\s*'([^']+)'/);
  if (syn) { sync[name] = syn[1]; continue; }

  // `ipcRenderer.on(channel, …)` where channel was built as `pty:data:${id}`.
  const addressed = body.match(/const channel = `([^`$]+)\$\{/);
  if (addressed) { ptyEvents[name] = addressed[1].replace(/:$/, ''); continue; }

  const on = body.match(/ipcRenderer\.on\(\s*'([^']+)'/);
  if (on) { events[name] = on[1]; }
}

const count = Object.keys(invoke).length;
if (count < 100) throw new Error(`only found ${count} invoke methods in preload — the parser is out of step`);

const lit = (o) => JSON.stringify(o, null, 2).replace(/"([a-zA-Z_][\w]*)":/g, '$1:').replace(/"/g, "'");
writeFileSync(join(ROOT, 'src/server/bridgeMap.generated.ts'), `/* GENERATED by tools/gen-bridge-map.cjs — do not edit.
 * Run \`npm run build:server\` (or the script directly) after changing preload. */

/** \`cth.method()\` → the channel it invokes. */
export const INVOKE: Record<string, string> = ${lit(invoke)};

/** Read synchronously at store construction, before the first render. */
export const SYNC: Record<string, string> = ${lit(sync)};

/** \`cth.onX(cb)\` → the channel main pushes on. */
export const EVENTS: Record<string, string> = ${lit(events)};

/** \`cth.onX(id, cb)\` → \`<channel>:<id>\`. */
export const PTY_EVENTS: Record<string, string> = ${lit(ptyEvents)};
`, 'utf8');

console.log(`[gen-bridge-map] ${count} methods, ${Object.keys(sync).length} sync, ${Object.keys(events).length} events, ${Object.keys(ptyEvents).length} pty events`);
